#!/usr/bin/env node
// Plays dweets in a real (headless) Chrome through the screensaver's own stage and reports which ones are
// broken, blank, static, flashing or hang. Needs Node 22.4+ and Chrome; no packages.
//
//   node tools/verify.mjs                          check the default selection (about 30 to 40 minutes)
//   node tools/verify.mjs --include "TOP_100"      check another selection (same syntax as INCLUDE, "|" between presets)
//   node tools/verify.mjs --write-blocklist        also update dwitter/blocklist.js with the failures
//   node tools/verify.mjs --soak                   rotation soak test: many fast rotations, watching memory
//   node tools/verify.mjs --help
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { launchBrowser, startServer } from "./lib/browser.mjs";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const siteDir = path.join(root, "dwitter");
const outDir = path.join(root, "tools", "out");
const Selection = require(path.join(siteDir, "selection.js"));
const Health = require(path.join(siteDir, "health.js"));

const HELP = `Usage: node tools/verify.mjs [options]

  --include <spec>      selection to check, same syntax as INCLUDE; separate several presets with |
                        (default: the default INCLUDE, MIN_LIKES_20 and CUSTOM)
  --all                 check every dweet in the database (takes hours)
  --only <ids>          check just these ids, comma separated
  --limit <n>           check only the first n dweets of the selection
  --concurrency <n>     browser windows at once (default 4)
  --write-blocklist     write the failures to dwitter/blocklist.js
  --fresh               ignore the existing blocklist, so blocklisted dweets are checked again
  --screenshots         keep a screenshot of every dweet (default: only of failures)
  --no-cache            ignore results from earlier runs
  --chrome <path>       Chrome, Chromium or Edge to use
  --soak                run the rotation soak test instead
  --rotations <n>       soak test: rotations to run (default 60)
`;

function parseArgs(argv) {
    const args = { concurrency: 4, rotations: 60, flags: new Set() };
    const withValue = new Set(["include", "only", "limit", "concurrency", "chrome", "rotations"]);
    for (let i = 0; i < argv.length; i++) {
        const name = argv[i].replace(/^--/, "");
        if (!argv[i].startsWith("--")) throw new Error("Unexpected argument: " + argv[i]);
        if (withValue.has(name)) {
            if (i + 1 >= argv.length) throw new Error("--" + name + " needs a value");
            args[name] = argv[++i];
        } else {
            args.flags.add(name);
        }
    }
    args.concurrency = Math.max(1, Number(args.concurrency) || 4);
    args.rotations = Math.max(3, Number(args.rotations) || 60);
    return args;
}

function loadDatabase(file) {
    if (!existsSync(file)) throw new Error("Database not found: " + file + "\nDownload it first: ./get-database.sh");
    const text = readFileSync(file, "utf8");
    const body = text.slice(text.indexOf("["), text.lastIndexOf("]") + 1).replace(/,\s*\]$/, "]");
    return JSON.parse(body); // parsed as data, never executed
}

function loadScriptValue(file, name, fallback) {
    if (!existsSync(file)) return fallback;
    return vm.runInNewContext(readFileSync(file, "utf8") + "\n;" + name, {});
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// Results only depend on how dweets are played and judged, so only these two files invalidate the cache.
function sourceVersion() {
    const text = ["runner.js", "health.js"].map((f) => readFileSync(path.join(siteDir, f), "utf8")).join("\n");
    return Selection.hashString(text);
}

function readJson(file, fallback) {
    try {
        return JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
        return fallback;
    }
}

function writeBlocklist(entries) {
    const ids = Object.keys(entries).sort((a, b) => (Number(a) || 0) - (Number(b) || 0) || a.localeCompare(b));
    const body = ids.map((id) => "    " + JSON.stringify(id) + ": " + JSON.stringify(entries[id]) + ",").join("\n");
    const text = `// Dweets that are known to be broken, blank, static or flashing: { id: "reason" }.
// Generated by tools/verify.mjs for the database snapshot it was run against:
//   node tools/verify.mjs --write-blocklist
// Dweets that are not listed here are still protected by the checks the screensaver runs while it plays.
const BLOCKLIST = {${ids.length ? "\n" + body + "\n" : ""}};
`;
    writeFileSync(path.join(siteDir, "blocklist.js"), text);
}

async function verifyOne(browser, baseUrl, dweet, options) {
    const started = Date.now();
    const tab = await browser.newTab(`${baseUrl}/index.html?id=${encodeURIComponent(dweet.id)}&rotate=0&minfps=0&mode=srcdoc`);
    const log = [];
    const pageErrors = [];
    tab.onMessage((kind, text) => { if (kind === "exception") pageErrors.push(text); });
    let hung = 0;
    let lastFrames = 0;
    let result = null;
    try {
        while (Date.now() - started < options.maxMs) {
            await sleep(300);
            let chunk;
            try {
                chunk = JSON.parse(await tab.evaluate("JSON.stringify(window.__dwitter ? window.__dwitter.log.splice(0) : [])", 3000));
                hung = 0;
            } catch (e) {
                if (++hung >= 2) { result = { verdict: "hang", detail: "the page stopped responding", metrics: {} }; break; }
                continue;
            }
            for (const entry of chunk) log.push(entry.msg);
            const stats = log.filter((m) => m.type === "stats");
            lastFrames = stats.length ? stats[stats.length - 1].frame : lastFrames;
            const early = Health.evaluateLog(log, { minFps: 0, static: false });
            if (early.verdict !== "ok" && early.verdict !== "incomplete") break;
            if (lastFrames >= options.frames) break;
        }
        if (!result) result = Health.evaluateLog(log, { minFps: 0 });
        if (result.verdict === "incomplete") result.detail = "only " + lastFrames + " frames in " + options.maxMs / 1000 + " s";
        if (pageErrors.length && result.verdict === "ok") result.pageErrors = pageErrors.slice(0, 2);
        if (options.screenshots || result.verdict !== "ok") {
            try {
                mkdirSync(path.join(outDir, "shots"), { recursive: true });
                writeFileSync(path.join(outDir, "shots", `${dweet.id}-${result.verdict}.png`), await tab.screenshot());
            } catch (e) {
                // A hung page cannot be photographed.
            }
        }
    } finally {
        await tab.close();
    }
    return { id: String(dweet.id), user: dweet.username, likes: dweet.awesome_count, usesText: /fillText|strokeText/.test(dweet.code), ms: Date.now() - started, ...result };
}

async function runVerify(args) {
    const flags = args.flags;
    const databaseFile = path.join(siteDir, "dweets.js");
    const blocklist = flags.has("fresh") ? {} : loadScriptValue(path.join(siteDir, "blocklist.js"), "BLOCKLIST", {});
    const db = Selection.buildDatabase({
        dweets: loadDatabase(databaseFile),
        custom: loadScriptValue(path.join(siteDir, "custom-dweets.js"), "CUSTOM_DWEETS", []),
        blocklist,
    });

    let include;
    if (flags.has("all")) include = ["ALL"];
    else if (args.only) include = ["IDS_" + args.only];
    else if (args.include) include = args.include.split("|");
    else include = loadScriptValue(path.join(siteDir, "config.js"), "CONFIG", {}).INCLUDE || Selection.DEFAULT_INCLUDE;
    let pool = Selection.resolve(db, { INCLUDE: include, EXCLUDE: [] }, { excludeInteractive: true }).pool;
    if (args.limit) pool = pool.slice(0, Number(args.limit));
    if (!pool.length) throw new Error("The selection is empty.");
    console.log(`Checking ${pool.length} dweets with ${args.concurrency} windows at a time...`);

    const version = sourceVersion();
    const cachePath = path.join(outDir, "cache.json");
    const cache = flags.has("no-cache") ? {} : readJson(cachePath, {});
    const server = await startServer(siteDir);
    const browser = await launchBrowser({ chrome: args.chrome });
    const results = [];
    const options = { frames: 240, maxMs: 14000, screenshots: flags.has("screenshots") };
    let next = 0;
    let done = 0;
    const startedAt = Date.now();

    async function worker() {
        while (next < pool.length) {
            const dweet = pool[next++];
            const key = `${dweet.id}:${Selection.hashString(dweet.code)}:${version}`;
            let result = cache[key];
            if (!result) {
                try {
                    result = await verifyOne(browser, server.url, dweet, options);
                } catch (e) {
                    result = { id: String(dweet.id), user: dweet.username, likes: dweet.awesome_count, verdict: "tool-error", detail: e.message, metrics: {} };
                }
                if (result.verdict !== "tool-error") cache[key] = result;
            }
            results.push(result);
            if (++done % 25 === 0 || done === pool.length) {
                const rate = (Date.now() - startedAt) / done;
                console.log(`  ${done}/${pool.length}  (about ${Math.round(rate * (pool.length - done) / 60000)} min left)`);
            }
        }
    }

    try {
        await Promise.all(Array.from({ length: args.concurrency }, worker));
    } finally {
        await browser.close();
        await server.close();
        mkdirSync(outDir, { recursive: true });
        writeFileSync(cachePath, JSON.stringify(cache));
    }

    const counts = {};
    for (const r of results) counts[r.verdict] = (counts[r.verdict] || 0) + 1;
    console.log("\nResults:", Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", "));

    const blocking = new Set(["compile-error", "runtime-error", "blank", "flash", "static", "hang"]);
    const failures = results.filter((r) => blocking.has(r.verdict)).sort((a, b) => Number(a.id) - Number(b.id));
    for (const r of failures) console.log(`  d/${r.id}  ${r.verdict}${r.detail ? " - " + r.detail : ""}  (@${r.user}, ${r.likes} likes)`);

    const incomplete = results.filter((r) => r.verdict === "incomplete");
    if (incomplete.length) console.log(`\nToo slow to judge here (not blocklisted, the screensaver skips slow dweets on the device): ${incomplete.map((r) => "d/" + r.id).join(", ")}`);
    const slow = results.filter((r) => r.verdict === "ok" && r.metrics.fps && r.metrics.fps < 45).sort((a, b) => a.metrics.fps - b.metrics.fps).slice(0, 15);
    if (slow.length) console.log(`\nSlowest here: ${slow.map((r) => `d/${r.id} ${r.metrics.fps}fps`).join(", ")}`);
    const text = results.filter((r) => r.usesText).map((r) => r.id);
    console.log(`\nDweets that draw text (worth a quick look, add any you dislike to EXCLUDE): ${text.length}`);

    writeFileSync(path.join(outDir, "report.json"), JSON.stringify({ when: new Date().toISOString(), include, results }, null, 1));
    console.log(`\nFull report: ${path.relative(root, path.join(outDir, "report.json"))}; screenshots of failures: tools/out/shots/`);

    if (flags.has("write-blocklist")) {
        const checked = new Set(pool.map((d) => String(d.id)));
        const merged = {};
        for (const [id, reason] of Object.entries(loadScriptValue(path.join(siteDir, "blocklist.js"), "BLOCKLIST", {}))) {
            if (!checked.has(id)) merged[id] = reason;
        }
        for (const r of failures) merged[r.id] = r.verdict;
        writeBlocklist(merged);
        console.log(`Wrote dwitter/blocklist.js with ${Object.keys(merged).length} dweets.`);
        return 0;
    }
    return failures.length ? 1 : 0;
}

async function runSoak(args) {
    const db = Selection.buildDatabase({
        dweets: loadDatabase(path.join(siteDir, "dweets.js")),
        custom: [],
        blocklist: loadScriptValue(path.join(siteDir, "blocklist.js"), "BLOCKLIST", {}),
    });
    const include = args.include || "TOP_40";
    const poolSize = Selection.resolve(db, { INCLUDE: include.split("|") }, { excludeInteractive: true }).pool.length;
    const server = await startServer(siteDir);
    const browser = await launchBrowser({ chrome: args.chrome });
    const samples = [];
    try {
        const tab = await browser.newTab(`${server.url}/index.html?debug=1&rotate=2&include=${encodeURIComponent(include)}`);
        await tab.send("HeapProfiler.enable");
        console.log(`Soak test: ${args.rotations} rotations, 2 s apart, pool of ${poolSize} (${include})...`);
        let lastSample = -1;
        const started = Date.now();
        for (;;) {
            await sleep(1000);
            const snap = JSON.parse(await tab.evaluate("JSON.stringify(window.__dwitter.snapshot())", 8000));
            if (snap.rotations >= lastSample + 4 || snap.rotations >= args.rotations) {
                lastSample = snap.rotations;
                await tab.send("HeapProfiler.collectGarbage", {}, 20000);
                const settled = JSON.parse(await tab.evaluate("JSON.stringify(window.__dwitter.snapshot())", 8000));
                samples.push(settled);
                if (samples.length % 3 === 0) console.log(`  rotation ${settled.rotations}: ${(settled.heap / 1048576).toFixed(1)} MB heap, ${settled.nodes} nodes, ${settled.iframes} iframes`);
            }
            if (snap.rotations >= args.rotations) break;
            if (Date.now() - started > args.rotations * 12000) throw new Error("The screensaver stopped rotating (only " + snap.rotations + " rotations).");
        }
        const failures = JSON.parse(await tab.evaluate("JSON.stringify(window.__dwitter.failures)"));
        await tab.close();

        const problems = [];
        const warm = samples.filter((s) => s.rotations >= 8);
        if (samples.some((s) => s.iframes > 3)) problems.push("more than 3 iframes alive at once");
        if (warm.length >= 4) {
            const nodes = warm.map((s) => s.nodes);
            if (Math.max(...nodes) - Math.min(...nodes) > 20) problems.push(`DOM node count drifts (${Math.min(...nodes)}..${Math.max(...nodes)})`);
            const quarter = Math.max(1, Math.floor(warm.length / 4));
            const avg = (list) => list.reduce((a, s) => a + s.heap, 0) / list.length;
            const growth = (avg(warm.slice(-quarter)) - avg(warm.slice(0, quarter))) / 1048576;
            console.log(`  heap change between the first and last quarter: ${growth.toFixed(1)} MB`);
            if (growth > 25) problems.push(`heap grew by ${growth.toFixed(1)} MB`);
        }
        if (failures.length) console.log(`  dweets skipped during the run: ${failures.map((f) => `d/${f.id} (${f.reason})`).join(", ")}`);
        if (problems.length) {
            console.log("Soak test FAILED: " + problems.join("; "));
            return 1;
        }
        console.log("Soak test passed.");
        return 0;
    } finally {
        await browser.close();
        await server.close();
    }
}

try {
    const args = parseArgs(process.argv.slice(2));
    if (args.flags.has("help") || args.flags.has("h")) {
        console.log(HELP);
        process.exit(0);
    }
    process.exitCode = await (args.flags.has("soak") ? runSoak(args) : runVerify(args));
} catch (e) {
    console.error(e.message);
    process.exitCode = 2;
}
